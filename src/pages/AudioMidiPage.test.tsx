import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { BrowserRouter } from 'react-router-dom'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { ThemeProvider } from '../theme/ThemeProvider'
import { AudioMidiPage } from './AudioMidiPage'
import type { MidiSource, SpectrumAnalyzer } from '../features/audio-midi/types'
import type { SpectralEditResult, SpectralRenderer } from '../features/spectral-edit/types'

vi.mock('./AudioMidiRoll', () => ({ AudioMidiRoll: () => <div aria-label="频谱 MIDI 编辑区" /> }))
const source = (): MidiSource => ({ name: 'song.wav', buffer: { duration: 3, sampleRate: 22050, numberOfChannels: 1 } as AudioBuffer,
  spectrum: { values: new Uint8Array(352), columns: 1, rows: 352, duration: 3, fftSize: 4096, sampleRate: 22050 } })
const file = () => new File(['audio'], 'song.wav', { type: 'audio/wav' })
function mount(analyzer: SpectrumAnalyzer = vi.fn().mockResolvedValue(source()), spectralRenderer?: SpectralRenderer) {
  return render(<BrowserRouter><ThemeProvider><AudioMidiPage analyzer={analyzer} spectralRenderer={spectralRenderer} /></ThemeProvider></BrowserRouter>)
}
const spectralOutput = (): SpectralEditResult => ({ blob: new Blob(['wave'], { type: 'audio/wav' }), preview: source(), sampleRate: 48000, channels: 2, frames: 144000, peak: .4, warnings: [] })
beforeEach(() => {
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:midi-export') })
  Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
  vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
  vi.spyOn(window, 'confirm').mockReturnValue(true)
})
afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('frequency-guided MIDI editor', () => {
  it('controls preview volume and follow mode, confirms clearing unsaved edits and can reload', async () => {
    const user = userEvent.setup(); mount()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await user.click(await screen.findByRole('button', { name: '添加音符' }))
    fireEvent.change(screen.getByLabelText('频谱试听音量'), { target: { value: '25' } })
    expect(screen.getByText('25%')).toBeVisible()
    await user.click(screen.getByLabelText('跟随播放'))
    expect(screen.getByLabelText('跟随播放')).not.toBeChecked()
    vi.mocked(window.confirm).mockReturnValueOnce(false)
    await user.click(screen.getByRole('button', { name: '清空音频' }))
    expect(screen.getByLabelText('频谱 MIDI 编辑区')).toBeVisible()
    await user.click(screen.getByRole('button', { name: '清空音频' }))
    expect(screen.queryByLabelText('频谱 MIDI 编辑区')).not.toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('已释放本机处理资源')
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    expect(await screen.findByLabelText('频谱 MIDI 编辑区')).toBeVisible()
    expect(screen.getByRole('button', { name: '导出 MIDI' })).toBeDisabled()
  })
  it('adds and edits notes, supports undo/redo and exports MIDI and an editable project', async () => {
    const view = mount(), user = userEvent.setup()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await screen.findByText('频谱已就绪。亮色横线表示较强的频率成分，沿基频画出音符即可。')
    expect(screen.getByRole('button', { name: '导出 MIDI' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: '添加音符' }))
    await user.selectOptions(screen.getByLabelText('选中音符音高'), '69')
    await user.clear(screen.getByLabelText('音符起点')); await user.type(screen.getByLabelText('音符起点'), '1')
    await user.clear(screen.getByLabelText('音符终点')); await user.type(screen.getByLabelText('音符终点'), '2')
    await user.click(screen.getByRole('button', { name: '应用音符修改' }))
    expect(screen.getByRole('heading', { name: '编辑 A4' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: '撤销' }))
    expect(screen.getByLabelText('选择已有音符')).toHaveTextContent('C4')
    await user.click(screen.getByRole('button', { name: '重做' }))
    expect(screen.getByLabelText('选择已有音符')).toHaveTextContent('A4')
    await user.click(screen.getByRole('button', { name: '导出 MIDI' }))
    expect(URL.createObjectURL).toHaveBeenCalledWith(expect.objectContaining({ type: 'audio/midi' }))
    await user.click(screen.getByRole('button', { name: '保存工程' }))
    expect(URL.createObjectURL).toHaveBeenCalledWith(expect.objectContaining({ type: 'application/json' }))
    view.unmount(); expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:midi-export')
  })
  it('cancels background analysis and ignores late completion, then retries', async () => {
    let resolve!: (value: MidiSource) => void
    const analyzer = vi.fn<SpectrumAnalyzer>().mockImplementationOnce(() => new Promise(done => { resolve = done })).mockResolvedValue(source())
    const user = userEvent.setup(); mount(analyzer)
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await user.click(screen.getByRole('button', { name: '停止分析' }))
    expect(analyzer.mock.calls[0][2].aborted).toBe(true)
    await act(async () => resolve(source()))
    expect(screen.queryByLabelText('频谱 MIDI 编辑区')).not.toBeInTheDocument()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    expect(await screen.findByLabelText('频谱 MIDI 编辑区')).toBeVisible()
  })
  it('validates BPM and audio errors and keeps existing notes when reanalysis fails', async () => {
    const analyzer = vi.fn<SpectrumAnalyzer>().mockResolvedValueOnce(source()).mockRejectedValue(new Error('无法解码此音频'))
    const user = userEvent.setup(); mount(analyzer)
    fireEvent.drop(screen.getByRole('region', { name: '频谱音频上传区' }), { dataTransfer: { files: [file()] } })
    await user.click(await screen.findByRole('button', { name: '添加音符' }))
    await user.clear(screen.getByLabelText('MIDI 速度 BPM'))
    expect(screen.getByRole('button', { name: '导出 MIDI' })).toBeDisabled()
    await user.type(screen.getByLabelText('MIDI 速度 BPM'), '120')
    await user.selectOptions(screen.getByLabelText('频谱精度'), '8192')
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('无法解码此音频'))
    expect(screen.getByLabelText('选择已有音符')).toHaveTextContent('C4')
    expect(screen.getByLabelText('频谱精度')).toHaveValue('4096')
    expect(screen.getByRole('button', { name: '导出 MIDI' })).toBeEnabled()
  })

  it('adds and edits spectral regions without deleting MIDI notes, previews versions and downloads WAV directly', async () => {
    const renderer = vi.fn<SpectralRenderer>().mockResolvedValue(spectralOutput())
    const view = mount(undefined, renderer), user = userEvent.setup()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await user.click(await screen.findByRole('button', { name: '添加音符' }))
    await user.click(screen.getByRole('button', { name: '去除频谱' }))
    await user.click(screen.getByRole('button', { name: '添加去除区域' }))
    await user.click(screen.getByRole('button', { name: '生成处理音频' }))
    const link = await screen.findByRole('link', { name: '下载去除后 WAV' })
    expect(link).toHaveAttribute('download', 'song-spectral-edited.wav')
    expect(renderer).toHaveBeenCalledWith(expect.any(File), [expect.objectContaining({ start: 0, end: 1, lowHz: 350, highHz: 550 })], 4096, expect.any(AbortSignal), expect.any(Function))
    expect(screen.getByLabelText('选择已有音符')).toHaveTextContent('C4')
    expect(screen.getByLabelText('频谱音频版本')).toHaveValue('processed')
    await user.selectOptions(screen.getByLabelText('频谱音频版本'), 'original')
    expect(screen.getByLabelText('试听内容')).toHaveTextContent('仅原音频')
    await user.click(screen.getByRole('button', { name: '删除选中区域' }))
    expect(screen.queryByRole('link', { name: '下载去除后 WAV' })).not.toBeInTheDocument()
    expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:midi-export')
    await user.click(screen.getByRole('button', { name: '撤销去除区域' }))
    expect(screen.getByLabelText('选择去除区域')).toHaveTextContent('350–550 Hz')
    await user.click(screen.getByRole('button', { name: '重做去除区域' }))
    expect(screen.getByRole('button', { name: '生成处理音频' })).toBeDisabled()
    expect(screen.getByLabelText('选择已有音符')).toHaveTextContent('C4')
    view.unmount()
  })

  it('validates spectral bounds, invalidates old output on edits and resets regions only after a new source succeeds', async () => {
    const renderer = vi.fn<SpectralRenderer>().mockResolvedValue(spectralOutput())
    const analyzer = vi.fn<SpectrumAnalyzer>().mockResolvedValue(source())
    mount(analyzer, renderer); const user = userEvent.setup()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await user.click(await screen.findByRole('button', { name: '去除频谱' }))
    await user.clear(screen.getByLabelText('去除最低频率')); await user.type(screen.getByLabelText('去除最低频率'), '600')
    await user.click(screen.getByRole('button', { name: '添加去除区域' }))
    expect(screen.getByRole('alert')).toHaveTextContent('最低频率须小于最高频率')
    await user.clear(screen.getByLabelText('去除最低频率')); await user.type(screen.getByLabelText('去除最低频率'), '300')
    await user.click(screen.getByRole('button', { name: '添加去除区域' }))
    await user.click(screen.getByRole('button', { name: '生成处理音频' })); await screen.findByRole('link', { name: '下载去除后 WAV' })
    await user.clear(screen.getByLabelText('去除终点')); await user.type(screen.getByLabelText('去除终点'), '2')
    await user.click(screen.getByRole('button', { name: '应用区域修改' }))
    expect(screen.queryByRole('link', { name: '下载去除后 WAV' })).not.toBeInTheDocument()
    expect(screen.getByLabelText('选择去除区域')).toHaveTextContent('0.00–2.00s')
    await user.selectOptions(screen.getByLabelText('频谱精度'), '8192')
    await waitFor(() => expect(screen.getByLabelText('频谱精度')).toHaveValue('8192'))
    expect(screen.getByLabelText('选择去除区域')).toHaveTextContent('0.00–2.00s')
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await waitFor(() => expect(screen.getByRole('button', { name: '生成处理音频' })).toBeDisabled())
    expect(window.confirm).toHaveBeenCalled()
  })

  it('cancels spectral processing, ignores late results, reports errors and releases output on unmount', async () => {
    let finish!: (value: SpectralEditResult) => void
    const renderer = vi.fn<SpectralRenderer>().mockImplementationOnce((_file, _regions, _size, _signal, progress) => {
      progress('正在去除指定频谱 50%…', 50)
      return new Promise(resolve => { finish = resolve })
    }).mockRejectedValueOnce(new Error('解码后超过 128 MB')).mockResolvedValue(spectralOutput())
    const view = mount(undefined, renderer), user = userEvent.setup()
    await user.upload(screen.getByLabelText('选择频谱音频文件'), file())
    await user.click(await screen.findByRole('button', { name: '去除频谱' }))
    await user.click(screen.getByRole('button', { name: '添加去除区域' }))
    await user.click(screen.getByRole('button', { name: '生成处理音频' }))
    expect(screen.getByLabelText('去除起点')).toBeDisabled()
    await user.click(screen.getByRole('button', { name: '停止频谱处理' }))
    expect(renderer.mock.calls[0][3].aborted).toBe(true)
    await act(async () => finish(spectralOutput()))
    expect(screen.queryByRole('link', { name: '下载去除后 WAV' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '生成处理音频' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('超过 128 MB')
    await user.click(screen.getByRole('button', { name: '生成处理音频' }))
    await screen.findByRole('link', { name: '下载去除后 WAV' })
    view.unmount(); expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:midi-export')
  })
})
